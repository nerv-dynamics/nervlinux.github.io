#!/usr/bin/env python3
"""Assemble the site from src/layout.html + src/pages/*.html.

No dependencies, no toolchain, no lockfile. Run `python3 build.py` and commit
the result; GitHub Pages serves the output directly.

Colour is not decided here. css/palette.css is generated from
src/vendor/palette.env, which nerv-theme declares to be the only place a Nerv
hex value may be written; run sync.py to refresh it. Everything the site adds
on top of those twelve roles lives in css/tokens.css and is named there as the
site's own.

Each page in src/pages/ starts with a metadata comment:

    <!--
    title: Platforms
    desc:  One-line description used for <title> and meta description.
    slug:  platforms          (omit or use "." for the front page)
    nav:   platforms          (which nav item to mark current)
    -->
"""

import html as _html
import pathlib
import re
import sys

import mdrender

ROOT = pathlib.Path(__file__).parent
SRC = ROOT / "src"
VENDOR = SRC / "vendor"

# palette.env names its roles NERV_<ROLE>; the site reads them as --nerv-<role>.
# Deliberately a straight transliteration and nothing more: the moment this
# function starts renaming or deriving, the site has an opinion about the
# palette and there are two sources of truth again.
PALETTE_NOTE = """\
/* ==========================================================================
   GENERATED by build.py from src/vendor/palette.env — do not edit.

   nerv-theme's palette.env is the source of truth for every Nerv colour:
   "nothing else may restate a hex value". This file is the web consumer of it,
   the way gen-env.sh is the shell consumer — one palette in, one drop-in out.

   To change a colour, change it in nerv-theme, then run sync.py.
   Anything the site needs that is NOT one of these twelve roles is defined in
   tokens.css and marked there as the site's own.
   ========================================================================== */
"""

# Copyright holder shown in the footer. Nerv Dynamics AB is a real legal
# entity, so it holds it; the earlier note here was written when the only
# candidate was a natural person, because an unincorporated trade name cannot
# hold a copyright and a trade name was all there was.
#
# The footer line is worth keeping even though the copyright itself is close to
# decorative: the trademark paragraph beside it is not, and an OEM's legal team
# reads that paragraph. Debian, Fedora, Arch and Ubuntu all carry the same
# furniture for the same reason.
OWNER = "Nerv Dynamics AB"

# The public source, or None while there is not one. Every page links to this
# from the footer, so a wrong value is a 404 across the whole site — which is
# what it was: github.com/nerv-dynamics/nerv-linux does not exist. The org does,
# so that is where this points until there is a repository to name. Change it
# the day there is one; a dead source link reads as vapour to the only audience
# that would ever click it.
SOURCE_URL = "https://github.com/nerv-dynamics"

# Five items. A nav is a promise about how much there is to read, so it stays
# short even when more pages exist; anything not here is reached from the page
# that owns it.
#
# "Features" points at /tools/ for now. The label is right and the URL is not,
# and moving it belongs to the session that rewrites that page.
NAV = [
    ("system",     "/system/",     "System"),
    ("tools",      "/tools/",      "Features"),
    ("enterprise", "/enterprise/", "Enterprise"),
    ("about",      "/about/",      "About"),
    ("handbook",   "/handbook/",   "Handbook"),
]


def write(path, text):
    """Write only if the content actually changed.

    Two reasons, and the second one is a bug that bit: an unchanged file keeps
    its mtime, so `git status` stays quiet and dev.py's watcher does not see a
    change. build.py generates css/palette.css INTO a directory dev.py watches,
    so an unconditional write meant every rebuild triggered the next one, once
    per poll interval, forever.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == text:
        return False
    path.write_text(text)
    return True


def render_palette():
    """src/vendor/palette.env -> css/palette.css."""
    env = VENDOR / "palette.env"
    if not env.is_file():
        sys.exit("src/vendor/palette.env is missing — run: python3 sync.py")

    roles = []
    for line in env.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        if not key.startswith("NERV_"):
            continue
        name = key[len("NERV_"):].lower().replace("_", "-")
        roles.append((name, value.strip()))

    if not roles:
        sys.exit("palette.env parsed to nothing — has its format changed?")

    width = max(len(n) for n, _ in roles)
    body = "\n".join(f"  --nerv-{n:<{width}}: #{v};" for n, v in roles)
    out = ROOT / "css" / "palette.css"
    changed = write(out, f"{PALETTE_NOTE}\n:root {{\n{body}\n}}\n")
    if changed:
        print(f"  palette.env          -> css/palette.css ({len(roles)} roles)")


def parse(text):
    """Split a page file into (metadata dict, body html)."""
    m = re.match(r"\s*<!--(.*?)-->\s*(.*)", text, re.S)
    if not m:
        sys.exit("page is missing its metadata comment")
    meta = {}
    for line in m.group(1).strip().splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta, m.group(2)


# --- the handbook -------------------------------------------------------
#
# Chapters are authored in the OS tree (handbook/, the public one) and copied
# here by sync.py. They are rendered, never re-written: the manual has one
# source, and it is next to the thing it documents.
HANDBOOK = VENDOR / "handbook"

# DISCIPLINE.md governs how a chapter is written. It is addressed to authors,
# not to operators, and publishing it would put the editorial rules on the
# same shelf as the instructions for installing the machine.
HANDBOOK_SKIP = {"DISCIPLINE.md"}


def handbook_slug(path):
    """src/vendor/handbook/machine/install.md -> handbook/machine/install"""
    rel = path.relative_to(HANDBOOK).with_suffix("")
    if rel.name == "README":
        rel = rel.parent
    return "/".join(["handbook", *rel.parts]).rstrip("/")


def handbook_link(source, href):
    """Rewrite a link as written in the OS tree into this site's URL space."""
    if re.match(r"^(https?:|mailto:|#|/)", href):
        return href
    target, _, anchor = href.partition("#")
    if not target.endswith(".md"):
        return href
    resolved = (source.parent / target).resolve()
    if resolved.name in HANDBOOK_SKIP:
        # Deliberately unpublished. Keep the words, drop the link, rather than
        # point a reader at a page this site does not serve.
        return None
    try:
        resolved.relative_to(HANDBOOK.resolve())
    except ValueError:
        # A chapter linking outside the published tree. The handbook's own
        # linter forbids reaching into docs/, so this is a broken link
        # upstream rather than something to paper over here.
        sys.exit(f"{source.name}: link escapes the handbook: {href}")
    url = "/" + handbook_slug(resolved) + "/"
    return url + (f"#{anchor}" if anchor else "")


def handbook_pages():
    """(slug, title, desc, html) for every published chapter."""
    if not HANDBOOK.is_dir():
        return []
    pages = []
    for path in sorted(HANDBOOK.rglob("*.md")):
        if path.name in HANDBOOK_SKIP:
            continue
        text = path.read_text()

        m = re.search(r"^#\s+(.*)$", text, re.M)
        title = m.group(1).strip() if m else path.stem.replace("-", " ")

        # The first real paragraph is the description. Skip headings, tables,
        # fences and the italic self-identification line chapters open with.
        desc = ""
        for block in re.split(r"\n\s*\n", text):
            b = " ".join(block.split())
            if b.startswith(("#", "|", "```", ">", "-", "*")):
                continue
            desc = re.sub(r"[*`\[\]]|\(.*?\)", "", b)
            break
        if len(desc) > 200:
            desc = desc[:197].rsplit(" ", 1)[0] + "..."

        try:
            body = mdrender.render(text, link=lambda h, s=path: handbook_link(s, h))
        except mdrender.MarkdownError as e:
            sys.exit(f"{path.relative_to(ROOT)}: {e}")

        pages.append((handbook_slug(path), title, desc, body))
    return pages


def render_source():
    """The footer's source link, or nothing at all if there is no repository."""
    if not SOURCE_URL:
        return ""
    return f'<a href="{SOURCE_URL}">Source</a>'


# Chapters are long-form, so they take .essay — which is where the serif and
# the narrow measure live. See docs/type.md.
HANDBOOK_WRAP = """<section class="section section--head">
  <div class="wrap">
    <p class="crumb"><a href="/handbook/">Handbook</a></p>
    <div class="essay">
{body}
    </div>
  </div>
</section>"""


REDIRECT = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Moved</title>
<link rel="canonical" href="https://nervlinux.org{to}">
<meta http-equiv="refresh" content="0; url={to}">
<meta name="robots" content="noindex">
</head>
<body>
<p>This page moved to <a href="{to}">{to}</a>.</p>
</body>
</html>
"""


def render_nav(current):
    out = []
    for key, href, label in NAV:
        cur = ' aria-current="page"' if key == current else ""
        out.append(f'<a href="{href}"{cur}>{label}</a>')
    return "\n      ".join(out)


def check_placeholders(pages_written):
    """Refuse to let an unresolved fact reach the built site.

    TKTK is the editorial marker for "a real number goes here". It exists so a
    layout can be built before the measurement is in, and the whole point is
    that it must be impossible to forget. Anything still carrying one is
    listed; --strict makes it an error, which is what a publish should use.
    """
    hits = []
    for path in pages_written:
        for i, line in enumerate(path.read_text().splitlines(), 1):
            if "TKTK" in line:
                hits.append((path.relative_to(ROOT), i, "TKTK", line.strip()[:60]))
            # A stand-in image. Marked in the markup rather than inferred from
            # the file, because a provisional screenshot looks exactly like a
            # real one to a build script and exactly like a real one to a
            # reader. Someone has to say so, once, in the page.
            if "shot--provisional" in line:
                hits.append((path.relative_to(ROOT), i, "provisional image",
                             line.strip()[:60]))
    # Empty image slots are counted but never fatal. A dashed frame saying
    # which file belongs in it is self-evidently unfinished, so it misleads
    # nobody; the point of --strict is to stop things that look real and are
    # not. Worth printing every build so they are not forgotten.
    slots = sum(p.read_text().count('class="slot"') for p in pages_written)
    if slots:
        print(f"\n  {slots} image slot(s) still empty (not an error)")

    if not hits:
        return
    print(f"\n  {len(hits)} unresolved placeholder(s):")
    for rel, i, kind, line in hits:
        print(f"    {rel}:{i}  [{kind}]  {line}")
    if "--strict" in sys.argv:
        sys.exit("\nrefusing to publish with unresolved placeholders")
    print("  (build.py --strict turns this into an error)")


def main():
    render_palette()
    layout = (SRC / "layout.html").read_text()
    written = []
    pages = sorted((SRC / "pages").glob("*.html"))
    if not pages:
        sys.exit("no pages found in src/pages/")

    for page in pages:
        meta, body = parse(page.read_text())
        slug = meta.get("slug", "").strip(" /")

        # A renamed page leaves its old URL behind as a redirect. GitHub Pages
        # serves no redirect rules, so the only mechanism available is a page
        # that refreshes — plus a canonical link, so search engines follow the
        # move rather than indexing two copies.
        if "redirect" in meta:
            dest = ROOT / slug / "index.html"
            write(dest, REDIRECT.format(to=meta["redirect"]))
            print(f"  {page.name:20} -> {dest.relative_to(ROOT)}  (redirect)")
            continue

        # The brand leads every title; the page name qualifies it.
        name = meta.get("title", "").strip()
        pagetitle = "Nerv Linux" if not slug else f"Nerv Linux \u2014 {name}"

        html = layout
        for key, value in {
            "title": name,
            "pagetitle": pagetitle,
            "desc": meta.get("desc", ""),
            "canonical": "https://nervlinux.org/" + (f"{slug}/" if slug else ""),
            "nav": render_nav(meta.get("nav", "")),
            "owner": OWNER,
            "source": render_source(),
            "content": body.rstrip(),
        }.items():
            html = html.replace("{{" + key + "}}", value)

        left = re.findall(r"\{\{(\w+)\}\}", html)
        if left:
            sys.exit(f"{page.name}: unreplaced placeholders {sorted(set(left))}")

        dest = ROOT / "index.html" if not slug else ROOT / slug / "index.html"
        write(dest, html)
        written.append(dest)
        print(f"  {page.name:20} -> {dest.relative_to(ROOT)}")

    # --- handbook chapters ---------------------------------------------
    chapters = handbook_pages()
    for slug, title, desc, body in chapters:
        html = layout
        for key, value in {
            "title": title,
            "pagetitle": f"Nerv Linux \u2014 {title}",
            "desc": desc,
            "canonical": f"https://nervlinux.org/{slug}/",
            "nav": render_nav("handbook"),
            "owner": OWNER,
            "source": render_source(),
            "content": HANDBOOK_WRAP.format(body=body),
        }.items():
            html = html.replace("{{" + key + "}}", value)
        left = re.findall(r"\{\{(\w+)\}\}", html)
        if left:
            sys.exit(f"{slug}: unreplaced placeholders {sorted(set(left))}")
        dest = ROOT / slug / "index.html"
        write(dest, html)
        written.append(dest)
        print(f"  {'handbook:' + slug.removeprefix('handbook'):20} -> "
              f"{dest.relative_to(ROOT)}")

    print(f"built {len(pages)} pages and {len(chapters)} handbook chapters")
    check_placeholders(written)


if __name__ == "__main__":
    main()
