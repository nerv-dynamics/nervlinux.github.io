#!/usr/bin/env python3
"""Assemble the site from src/layout.html + src/pages/*.html.

No dependencies, no toolchain, no lockfile. Run `python3 build.py` and commit
the result; GitHub Pages serves the output directly.

Colour is not decided here. css/palette.css is generated from
src/vendor/palette.env, which nerv-theme declares to be the only place a Nerv
hex value may be written; run sync.py to refresh it. Everything the site adds
on top of those twelve roles lives in css/tokens.css and is named there as the
site's own.

Each page in src/pages/ starts with a metadata comment:

    <!--
    title: Platforms
    desc:  One-line description used for <title> and meta description.
    slug:  platforms          (omit or use "." for the front page)
    nav:   platforms          (which nav item to mark current)
    -->
"""

import html as _html
import pathlib
import re
import sys

import mdrender

ROOT = pathlib.Path(__file__).parent
SRC = ROOT / "src"
VENDOR = SRC / "vendor"

# Myelin is the OS's colour scheme, exported as CSS by nerv-theme's own
# generator. The site does not restate a single value from it.
#
# One transformation is needed. Myelin is light-first and switches on
# prefers-color-scheme; this site is dark-first with a manual toggle that
# writes data-theme. So the generated file repeats each block under the
# matching [data-theme] selector, which lets the toggle override the OS
# preference in both directions without anyone retyping a hex.
PALETTE_NOTE = """\
/* ==========================================================================
   GENERATED by build.py from src/vendor/myelin.css — do not edit.

   Myelin is the Nerv colour scheme. nerv-theme generates it from
   myelin.palette, and the site consumes it the way the terminal and the
   desktop do: nothing here is a second opinion about a colour.

   build.py adds the [data-theme] selectors. Myelin switches on
   prefers-color-scheme, and this site also has a manual toggle, so each
   block is emitted twice: once as Myelin wrote it, once under the theme
   attribute. The values are never retyped.

   To change a colour, change myelin.palette in nerv-theme and re-export.
   ========================================================================== */
"""

# Copyright holder shown in the footer. Nerv Dynamics AB is a real legal
# entity, so it holds it; the earlier note here was written when the only
# candidate was a natural person, because an unincorporated trade name cannot
# hold a copyright and a trade name was all there was.
#
# The footer line is worth keeping even though the copyright itself is close to
# decorative: the trademark paragraph beside it is not, and an OEM's legal team
# reads that paragraph. Debian, Fedora, Arch and Ubuntu all carry the same
# furniture for the same reason.
OWNER = "Nerv Dynamics AB"

# The public source, or None while there is not one. Every page links to this
# from the footer, so a wrong value is a 404 across the whole site — which is
# what it was: github.com/nerv-dynamics/nerv-linux does not exist. The org does,
# so that is where this points until there is a repository to name. Change it
# the day there is one; a dead source link reads as vapour to the only audience
# that would ever click it.
SOURCE_URL = "https://github.com/nerv-dynamics"

# Six items. A nav is a promise about how much there is to read, so it stays
# short even when more pages exist; anything not here is reached from the page
# that owns it.
NAV = [
    ("system",     "/system/",     "System"),
    ("desktop",    "/desktop/",    "Desktop"),
    ("enterprise", "/enterprise/", "Enterprise"),
    ("community",  "/community/",  "Community"),
    ("handbook",   "/handbook/",   "Handbook"),
    ("about",      "/about/",      "About"),
]


def write(path, text):
    """Write only if the content actually changed.

    Two reasons, and the second one is a bug that bit: an unchanged file keeps
    its mtime, so `git status` stays quiet and dev.py's watcher does not see a
    change. build.py generates css/palette.css INTO a directory dev.py watches,
    so an unconditional write meant every rebuild triggered the next one, once
    per poll interval, forever.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == text:
        return False
    path.write_text(text)
    return True


def render_palette():
    """src/vendor/myelin.css -> css/palette.css, dark-first.

    Myelin is light-first and switches on prefers-color-scheme. This site has
    been dark by default since the theme was added, the hero is artwork built
    for a dark ground, and the wordmark ships as two files chosen by theme, so
    flipping the default would be a redesign rather than a recolour.

    So the blocks are swapped: Myelin's dark values become :root, and its
    light values apply only when the toggle asks. No value is retyped, and
    changing a colour still means changing myelin.palette in nerv-theme.
    """
    src = VENDOR / "myelin.css"
    if not src.is_file():
        sys.exit("src/vendor/myelin.css is missing — copy it from nerv-theme")
    css = src.read_text()

    m = re.search(r":root\s*\{(.*?)\n\}", css, re.S)
    if not m:
        sys.exit("myelin.css: could not find the :root block")
    light = m.group(1).replace("\n  color-scheme: light;", "")

    m = re.search(r"@media \(prefers-color-scheme: dark\)\s*\{\s*"
                  r":root\s*\{(.*?)\n  \}", css, re.S)
    if not m:
        sys.exit("myelin.css: could not find the dark block")
    dark = "\n".join(l[2:] if l.startswith("    ") else l
                     for l in m.group(1).splitlines())
    dark = dark.replace("\n  color-scheme: dark;", "")

    # The neutral scale is absolute and declared once, in Myelin's :root. The
    # semantic tokens point into it and are what actually flip. Splitting them
    # matters: swapping the blocks wholesale left the dark defaults referring
    # to n-scale tokens that only existed inside the light selector.
    scale = [l for l in light.splitlines() if re.match(r"\s*--myelin-n\d+:", l)]
    light_sem = [l for l in light.splitlines()
                 if not re.match(r"\s*--myelin-n\d+:", l)]

    out = [PALETTE_NOTE,
           "/* The neutral scale. Absolute, and the same in both themes. */",
           ":root {\n" + "\n".join(scale) + "\n}",
           "",
           "/* Dark is the default. Myelin's dark values, verbatim. */",
           ":root {" + dark + "\n  color-scheme: dark;\n}",
           "",
           "/* Light, when the toggle asks for it. Myelin's light values, verbatim. */",
           ':root[data-theme="light"] {\n' + "\n".join(light_sem)
           + "\n  color-scheme: light;\n}",
           "",
           "/* A subtree that is dark whatever the page is doing. The hero is",
           "   artwork with its own ground, so it keeps Myelin's dark values even",
           "   under the light theme. Redeclaring the semantic tokens here means",
           "   everything inside resolves to them through ordinary inheritance,",
           "   so no component has to know it is sitting on a dark panel. */",
           ".on-dark {" + dark + "\n  color-scheme: dark;\n}",
           ""]
    if write(ROOT / "css" / "palette.css", "\n".join(out)):
        n = len(re.findall(r"--myelin-[a-z0-9-]+:", dark))
        print(f"  myelin.css           -> css/palette.css ({n} tokens, dark-first)")


def parse(text):
    """Split a page file into (metadata dict, body html)."""
    m = re.match(r"\s*<!--(.*?)-->\s*(.*)", text, re.S)
    if not m:
        sys.exit("page is missing its metadata comment")
    meta = {}
    for line in m.group(1).strip().splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta, m.group(2)


# --- the handbook -------------------------------------------------------
#
# Chapters are authored in the OS tree (handbook/, the public one) and copied
# here by sync.py. They are rendered, never re-written: the manual has one
# source, and it is next to the thing it documents.
HANDBOOK = VENDOR / "handbook"

# DISCIPLINE.md governs how a chapter is written. It is addressed to authors,
# not to operators, and publishing it would put the editorial rules on the
# same shelf as the instructions for installing the machine.
HANDBOOK_SKIP = {"DISCIPLINE.md", "README.md"}

# The table of contents, in reading order. README.md in the OS tree is the
# authors' map (planned slots, the editorial frame); the reader's front page
# is generated from this list and the chapters' own front matter instead, so
# it only ever shows chapters that exist. A chapter missing from this list is
# still published, at the end, under "More".
HANDBOOK_TOC = [
    ("Getting started", [
        "machine/why-an-operating-system-still",
        "machine/install",
        "machine/the-first-hour",
    ]),
]


def handbook_slug(path):
    """src/vendor/handbook/machine/install.md -> handbook/machine/install"""
    rel = path.relative_to(HANDBOOK).with_suffix("")
    if rel.name == "README":
        rel = rel.parent
    return "/".join(["handbook", *rel.parts]).rstrip("/")


def handbook_link(source, href):
    """Rewrite a link as written in the OS tree into this site's URL space."""
    if re.match(r"^(https?:|mailto:|#|/)", href):
        return href
    target, _, anchor = href.partition("#")
    if not target.endswith(".md"):
        return href
    resolved = (source.parent / target).resolve()
    if resolved.name in HANDBOOK_SKIP:
        # Deliberately unpublished. Keep the words, drop the link, rather than
        # point a reader at a page this site does not serve.
        return None
    try:
        resolved.relative_to(HANDBOOK.resolve())
    except ValueError:
        # A chapter linking outside the published tree. The handbook's own
        # linter forbids reaching into docs/, so this is a broken link
        # upstream rather than something to paper over here.
        sys.exit(f"{source.name}: link escapes the handbook: {href}")
    url = "/" + handbook_slug(resolved) + "/"
    return url + (f"#{anchor}" if anchor else "")


def front_matter(text):
    """Split a chapter's leading `---` block into (keys, rest).

    The keys are flat `name: value` pairs; an indented line continues the
    value above it, which is how a long one-line wraps in the source."""
    m = re.match(r"\A---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}, text
    keys, last = {}, None
    for line in m.group(1).split("\n"):
        if line[:1].isspace() and last:
            keys[last] += " " + line.strip()
            continue
        k, sep, v = line.partition(":")
        if sep:
            last = k.strip()
            keys[last] = v.strip()
    return keys, text[m.end():]


def handbook_pages():
    """Chapters in table-of-contents order, as dicts."""
    if not HANDBOOK.is_dir():
        return []
    found = {}
    for path in sorted(HANDBOOK.rglob("*.md")):
        if path.name in HANDBOOK_SKIP:
            continue
        keys, text = front_matter(path.read_text())

        m = re.search(r"^#\s+(.*)$", text, re.M)
        title = keys.get("title") or (m.group(1).strip() if m else path.stem.replace("-", " "))
        desc = keys.get("one-line", "")

        try:
            body = mdrender.render(text, link=lambda h, s=path: handbook_link(s, h))
        except mdrender.MarkdownError as e:
            sys.exit(f"{path.relative_to(ROOT)}: {e}")

        sections = [(i, re.sub(r"<[^>]+>", "", t)) for i, t in
                    re.findall(r'<h2 id="([^"]+)"[^>]*>(.*?)</h2>', body)]
        key = str(path.relative_to(HANDBOOK).with_suffix(""))
        found[key] = {"slug": handbook_slug(path), "title": title, "desc": desc,
                      "body": body, "sections": sections}

    parts = []
    for name, keys in HANDBOOK_TOC:
        chapters = [found.pop(k) for k in keys if k in found]
        if chapters:
            parts.append((name, chapters))
    if found:
        parts.append(("More", list(found.values())))
    for name, chapters in parts:
        for c in chapters:
            c["part"] = name
    return parts


def handbook_sidebar(parts, current=None):
    """The left-hand contents. The open chapter lists its own sections."""
    out = ['<nav class="hb-nav" aria-label="Handbook">',
           '<details class="hb-nav__box" open>',
           '<summary class="hb-nav__summary">Contents</summary>',
           '<a class="hb-nav__home" href="/handbook/">The Nerv Handbook</a>']
    for name, chapters in parts:
        out.append(f'<p class="hb-nav__part">{_html.escape(name)}</p><ol class="hb-nav__list">')
        for c in chapters:
            cur = c is current
            attr = ' aria-current="page"' if cur else ""
            out.append(f'<li><a href="/{c["slug"]}/"{attr}>{_html.escape(c["title"])}</a>')
            if cur and c["sections"]:
                out.append('<ol class="hb-nav__sections">')
                for sid, label in c["sections"]:
                    out.append(f'<li><a href="#{sid}">{label}</a></li>')
                out.append("</ol>")
            out.append("</li>")
        out.append("</ol>")
    out.append("</details></nav>")
    return "\n".join(out)


def handbook_pager(flat, i):
    """Previous and next chapter, in reading order."""
    cells = []
    if i > 0:
        p = flat[i - 1]
        cells.append(f'<a class="hb-pager__prev" href="/{p["slug"]}/"><span>Previous</span>{_html.escape(p["title"])}</a>')
    else:
        cells.append("<span></span>")
    if i + 1 < len(flat):
        n = flat[i + 1]
        cells.append(f'<a class="hb-pager__next" href="/{n["slug"]}/"><span>Next</span>{_html.escape(n["title"])}</a>')
    return '<nav class="hb-pager" aria-label="Chapters">' + "".join(cells) + "</nav>"


def handbook_index(parts):
    """The handbook's front page: what it is, then every chapter."""
    out = ['<h1 class="page-title">The Nerv Handbook</h1>',
           '<p class="lead">How to install Nerv, use it every day, and run it across many machines.</p>']
    for name, chapters in parts:
        out.append(f'<h2 class="section-title">{_html.escape(name)}</h2><ol class="hb-toc">')
        for c in chapters:
            out.append(f'<li><a href="/{c["slug"]}/">{_html.escape(c["title"])}</a>'
                       f'<p>{_html.escape(c["desc"])}</p></li>')
        out.append("</ol>")
    return "\n".join(out)


def render_source():
    """The footer's source link, or nothing at all if there is no repository."""
    if not SOURCE_URL:
        return ""
    return f'<a href="{SOURCE_URL}">Source</a>'


# Chapters are long-form, so they take .essay — which is where the serif and
# the narrow measure live. See docs/type.md.
HANDBOOK_WRAP = """<section class="section section--head">
  <div class="wrap hb">
    {sidebar}
    <div class="hb__main">
      <div class="essay">
{body}
      </div>
      {pager}
    </div>
  </div>
</section>"""


REDIRECT = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Moved</title>
<link rel="canonical" href="https://nervlinux.org{to}">
<meta http-equiv="refresh" content="0; url={to}">
<meta name="robots" content="noindex">
</head>
<body>
<p>This page moved to <a href="{to}">{to}</a>.</p>
</body>
</html>
"""


def render_nav(current):
    out = []
    for key, href, label in NAV:
        cur = ' aria-current="page"' if key == current else ""
        out.append(f'<a href="{href}"{cur}>{label}</a>')
    return "\n      ".join(out)


def check_placeholders(pages_written):
    """Refuse to let an unresolved fact reach the built site.

    TKTK is the editorial marker for "a real number goes here". It exists so a
    layout can be built before the measurement is in, and the whole point is
    that it must be impossible to forget. Anything still carrying one is
    listed; --strict makes it an error, which is what a publish should use.
    """
    hits = []
    for path in pages_written:
        for i, line in enumerate(path.read_text().splitlines(), 1):
            if "TKTK" in line:
                hits.append((path.relative_to(ROOT), i, "TKTK", line.strip()[:60]))
            # A stand-in image. Marked in the markup rather than inferred from
            # the file, because a provisional screenshot looks exactly like a
            # real one to a build script and exactly like a real one to a
            # reader. Someone has to say so, once, in the page.
            if "shot--provisional" in line:
                hits.append((path.relative_to(ROOT), i, "provisional image",
                             line.strip()[:60]))
    # Empty image slots are counted but never fatal. A dashed frame saying
    # which file belongs in it is self-evidently unfinished, so it misleads
    # nobody; the point of --strict is to stop things that look real and are
    # not. Worth printing every build so they are not forgotten.
    slots = sum(p.read_text().count('class="slot"') for p in pages_written)
    if slots:
        print(f"\n  {slots} image slot(s) still empty (not an error)")

    if not hits:
        return
    print(f"\n  {len(hits)} unresolved placeholder(s):")
    for rel, i, kind, line in hits:
        print(f"    {rel}:{i}  [{kind}]  {line}")
    if "--strict" in sys.argv:
        sys.exit("\nrefusing to publish with unresolved placeholders")
    print("  (build.py --strict turns this into an error)")


def main():
    render_palette()
    layout = (SRC / "layout.html").read_text()
    written = []
    pages = sorted((SRC / "pages").glob("*.html"))
    if not pages:
        sys.exit("no pages found in src/pages/")

    for page in pages:
        meta, body = parse(page.read_text())
        slug = meta.get("slug", "").strip(" /")

        # A renamed page leaves its old URL behind as a redirect. GitHub Pages
        # serves no redirect rules, so the only mechanism available is a page
        # that refreshes — plus a canonical link, so search engines follow the
        # move rather than indexing two copies.
        if "redirect" in meta:
            dest = ROOT / slug / "index.html"
            write(dest, REDIRECT.format(to=meta["redirect"]))
            print(f"  {page.name:20} -> {dest.relative_to(ROOT)}  (redirect)")
            continue

        # The brand leads every title; the page name qualifies it.
        name = meta.get("title", "").strip()
        pagetitle = "Nerv Linux" if not slug else f"Nerv Linux \u2014 {name}"

        html = layout
        for key, value in {
            "title": name,
            "pagetitle": pagetitle,
            "desc": meta.get("desc", ""),
            "canonical": "https://nervlinux.org/" + (f"{slug}/" if slug else ""),
            "nav": render_nav(meta.get("nav", "")),
            "owner": OWNER,
            "source": render_source(),
            "content": body.rstrip(),
        }.items():
            html = html.replace("{{" + key + "}}", value)

        left = re.findall(r"\{\{(\w+)\}\}", html)
        if left:
            sys.exit(f"{page.name}: unreplaced placeholders {sorted(set(left))}")

        dest = ROOT / "index.html" if not slug else ROOT / slug / "index.html"
        write(dest, html)
        written.append(dest)
        print(f"  {page.name:20} -> {dest.relative_to(ROOT)}")

    # --- handbook chapters ---------------------------------------------
    parts = handbook_pages()
    flat = [c for _, chapters in parts for c in chapters]
    hb_pages = [("handbook", "Handbook", "The Nerv Handbook: how to install Nerv, use it every day, and run it across many machines.",
                 HANDBOOK_WRAP.format(sidebar=handbook_sidebar(parts), body=handbook_index(parts), pager=""))]
    for i, c in enumerate(flat):
        hb_pages.append((c["slug"], c["title"], c["desc"],
                         HANDBOOK_WRAP.format(sidebar=handbook_sidebar(parts, c), body=c["body"],
                                              pager=handbook_pager(flat, i))))
    for slug, title, desc, content in hb_pages:
        html_out = layout
        for key, value in {
            "title": title,
            "pagetitle": f"Nerv Linux \u2014 {title}",
            "desc": desc,
            "canonical": f"https://nervlinux.org/{slug}/",
            "nav": render_nav("handbook"),
            "owner": OWNER,
            "source": render_source(),
            "content": content,
        }.items():
            html_out = html_out.replace("{{" + key + "}}", value)
        left = re.findall(r"\{\{(\w+)\}\}", html_out)
        if left:
            sys.exit(f"{slug}: unreplaced placeholders {sorted(set(left))}")
        dest = ROOT / slug / "index.html"
        write(dest, html_out)
        written.append(dest)
        print(f"  {'handbook:' + slug.removeprefix('handbook'):20} -> "
              f"{dest.relative_to(ROOT)}")
    chapters = flat

    print(f"built {len(pages)} pages and {len(chapters)} handbook chapters")
    check_placeholders(written)


if __name__ == "__main__":
    main()
