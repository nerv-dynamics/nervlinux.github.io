#!/usr/bin/env python3
"""Preview the site locally: rebuild on save, reload the browser.

    python3 dev.py                  # 0.0.0.0:8000 — reachable from the LAN
    python3 dev.py 9000             # another port
    python3 dev.py --local          # 127.0.0.1 only
    python3 dev.py --host 10.0.0.5  # one interface

Stdlib only, like build.py. Editing anything under src/, css/ or assets/
re-runs the build and the open tab reloads itself.

It binds every interface by default, so the site can be checked from a phone
or another box on the network — which is the only way to see whether the type
and the hero actually work on a small screen. That also means anyone who can
reach this port can read the repository directory, so it is a tool for a
trusted network, not something to leave running on a public one. `--local`
puts it back on the loopback.

The reload script is injected by this server as it serves a page; it is never
written to disk, so the committed HTML stays exactly what GitHub Pages gets.
"""

import functools
import http.server
import importlib
import pathlib
import socketserver
import sys
import threading
import time
import traceback

import build
import mdrender

ROOT = pathlib.Path(__file__).parent
WATCH = ["src", "css", "assets", "fonts", "build.py", "mdrender.py"]
# Generated by build.py into a watched directory. build.py no longer rewrites
# it when nothing changed, and excluding it here means a real edit to the
# palette still cannot start a rebuild loop.
IGNORE = {"css/palette.css"}
POLL = 0.3

# Bumped on every successful rebuild. The page polls it and reloads when it
# changes, which is the whole of the live-reload protocol.
revision = 0

RELOAD_JS = """
<script>
/* injected by dev.py — not present in the built site */
(function () {
  var mine = null;
  setInterval(function () {
    fetch('/__dev/rev').then(function (r) { return r.text(); }).then(function (v) {
      if (mine === null) { mine = v; return; }
      if (v !== mine) location.reload();
    }).catch(function () {});
  }, 500);
})();
</script>
"""


def stamp():
    """Cheapest thing that changes when any watched file does."""
    out = []
    for name in WATCH:
        path = ROOT / name
        if path.is_file():
            out.append((str(path), path.stat().st_mtime_ns))
            continue
        for f in sorted(path.rglob("*")):
            if f.is_file() and str(f.relative_to(ROOT)) not in IGNORE:
                out.append((str(f), f.stat().st_mtime_ns))
    return tuple(out)


def watch():
    global revision
    last = stamp()
    while True:
        time.sleep(POLL)
        now = stamp()
        if now == last:
            continue
        last = now
        print("\n— change detected, rebuilding")
        try:
            # Re-import before rebuilding. Python caches a module at import
            # time, so a long-running server holds whatever build.py said when
            # it started. Editing the build script would be DETECTED (it is
            # watched) and then rebuilt with the stale code, silently reverting
            # the output. Reload mdrender first, since build imports it.
            importlib.reload(mdrender)
            importlib.reload(build)
            build.main()
            revision += 1
        except SystemExit as e:          # build.py reports its own errors this way
            print(f"  build failed: {e}")
        except Exception:
            traceback.print_exc()


class Handler(http.server.SimpleHTTPRequestHandler):
    def do_GET(self):
        if self.path.startswith("/__dev/rev"):
            body = str(revision).encode()
            self.send_response(200)
            self.send_header("Content-Type", "text/plain")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)
            return

        target = self.resolve()
        if target is not None:
            html = target.read_text()
            if "</body>" in html:
                html = html.replace("</body>", RELOAD_JS + "</body>", 1)
            body = html.encode()
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)
            return

        super().do_GET()

    def resolve(self):
        """The .html file this request maps to, or None if it isn't one."""
        path = self.translate_path(self.path)
        p = pathlib.Path(path)
        if p.is_dir():
            p = p / "index.html"
        return p if p.is_file() and p.suffix == ".html" else None

    def end_headers(self):
        # Nothing here should ever be cached during development.
        if "Cache-Control" not in self._headers_buffer_names():
            self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def _headers_buffer_names(self):
        return [
            h.decode(errors="replace").split(":", 1)[0]
            for h in getattr(self, "_headers_buffer", [])
        ]

    def log_message(self, fmt, *args):
        if "/__dev/rev" in (args[0] if args else ""):
            return
        super().log_message(fmt, *args)


def lan_address():
    """The address another machine on the network would use to reach us.

    Connecting a UDP socket sends nothing, but it makes the kernel choose a
    source address using the real routing table — which is what we want to
    print. Reading the hostname instead tends to answer 127.0.0.1.
    """
    import socket
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            s.connect(("192.0.2.1", 1))   # reserved, unrouted, never contacted
            return s.getsockname()[0]
        finally:
            s.close()
    except OSError:
        return None


def main():
    args = sys.argv[1:]
    host = "0.0.0.0"
    port = 8000
    while args:
        a = args.pop(0)
        if a == "--local":
            host = "127.0.0.1"
        elif a == "--host":
            if not args:
                sys.exit("--host needs an address")
            host = args.pop(0)
        elif a.isdigit():
            port = int(a)
        else:
            sys.exit(f"unexpected argument: {a}")

    build.main()
    threading.Thread(target=watch, daemon=True).start()

    handler = functools.partial(Handler, directory=str(ROOT))
    socketserver.ThreadingTCPServer.allow_reuse_address = True
    with socketserver.ThreadingTCPServer((host, port), handler) as httpd:
        # flush: piped or run under a multiplexer, stdout is block-buffered and
        # the address would not appear until the first request.
        print(f"\n  nervlinux.org  ->  http://localhost:{port}", flush=True)
        if host == "0.0.0.0":
            lan = lan_address()
            if lan:
                print(f"                     http://{lan}:{port}   (from other machines)",
                      flush=True)
        elif host != "127.0.0.1":
            print(f"                     http://{host}:{port}", flush=True)
        print("  watching src/ css/ assets/ fonts/ — Ctrl-C to stop\n", flush=True)
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            print("\nstopped")


if __name__ == "__main__":
    main()
